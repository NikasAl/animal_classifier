"""Конструктор промптов. Три режима:

- closed:    список пород-кандидатов, строгий JSON {"is_<pet>": bool, "guesses": [...]}
- open:      свободный ответ (без списка кандидатов)
- reasoning: список кандидатов + требование сначала перечислить наблюдаемые
             признаки (analysis), затем guesses. Проверяет, помогает ли
             явный CoT повысить точность.
"""


def _breed_list_line(breeds: list[str]) -> str:
    return ", ".join(breeds)


def build_prompts(species_cfg: dict, mode: str, breeds: list[str] | None = None) -> tuple[str, str]:
    """Возвращает (system, user) для заданного режима.

    breeds — список названий пород-кандидатов (для closed/reasoning).
    """
    pet_rus = species_cfg.get("species_rus", "питомец")
    is_pet_field = species_cfg.get("is_pet_field", "is_pet")
    unrecognized = ", ".join(species_cfg.get("unrecognized_markers", [])[:4])

    system = (
        f"Ты — опытный эксперт-зоолог с 30-летним стажем определения пород {pet_rus} по фотографиям. "
        "Ты судишь на выставках и точно знаешь экстерьерные признаки каждой породы. "
        "Отвечай СТРОГО валидным JSON без markdown-обёрток, без пояснений вне JSON."
    )

    if mode == "closed":
        user = (
            f"Определи породу {pet_rus} на фотографии.\n"
            f"Список пород-кандидатов: {_breed_list_line(breeds)}.\n\n"
            "Правила:\n"
            "1. Выбирай породу ТОЛЬКО из списка кандидатов (название пиши точно как в списке).\n"
            "2. Верни топ-3 наиболее вероятных породы в порядке убывания уверенности.\n"
            "3. confidence — целое число от 0 до 100.\n"
            f"4. Если на фото нет {pet_rus[:-1] + 'а' if pet_rus.endswith('а') else pet_rus} или породу невозможно определить — верни "
            f'{{"{is_pet_field}": false, "guesses": []}}.\n\n'
            f'Формат ответа (строгий JSON): {{"{is_pet_field}": true, "guesses": [{{"breed": "<название из списка>", "confidence": 85}}, ...]}}'
        )
        return system, user

    if mode == "reasoning":
        user = (
            f"Определи породу {pet_rus} на фотографии.\n"
            f"Список пород-кандидатов: {_breed_list_line(breeds)}.\n\n"
            "Порядок работы:\n"
            "1. Сначала внимательно опиши наблюдаемые признаки: размер и телосложение, форма морды, "
            "форма и постав ушей, тип и длина шерсти, окрас и отметины, хвост, иные отличительные черты.\n"
            "2. Сопоставь эти признаки с породами из списка кандидатов.\n"
            "3. Выбери топ-3 наиболее вероятных породы в порядке убывания уверенности. "
            "Первый элемент guesses должен логически следовать из analysis.\n"
            "4. confidence — целое число от 0 до 100. Название породы — ТОЧНО из списка кандидатов.\n\n"
            f'Формат ответа (строгий JSON): {{"{is_pet_field}": true, "analysis": ["признак 1", "признак 2", "признак 3"], '
            '"guesses": [{"breed": "<название из списка>", "confidence": 85}, ...]}}'
        )
        return system, user

    if mode == "open":
        user = (
            f"Определи породу {pet_rus} на фотографии. Можно называть любую породу мира.\n"
            "Правила:\n"
            "1. Верни топ-3 наиболее вероятных породы в порядке убывания уверенности.\n"
            "2. confidence — целое число от 0 до 100.\n"
            f"3. Если на фото нет {pet_rus} — верни {{\"{is_pet_field}\": false, \"guesses\": []}}.\n"
            f"4. Если {pet_rus} беспородная(-ой), метис или породу определить невозможно — так и напиши "
            f"(например \"{unrecognized}\").\n\n"
            f'Формат ответа (строгий JSON): {{"{is_pet_field}": true, "guesses": [{{"breed": "<порода>", "confidence": 85}}, ...]}}'
        )
        return system, user

    raise ValueError(f"Unknown mode: {mode}")
